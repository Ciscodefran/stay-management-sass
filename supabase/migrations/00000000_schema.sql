CREATE SCHEMA IF NOT EXISTS "org";  -- 조직/테넌트 관리
CREATE SCHEMA IF NOT EXISTS "ref";  -- 참조/조회 테이블
CREATE SCHEMA IF NOT EXISTS "pub";  -- 공개 구체화 뷰
